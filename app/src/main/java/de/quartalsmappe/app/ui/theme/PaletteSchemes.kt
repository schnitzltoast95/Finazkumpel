private fun paletteColors(
    darkTheme: Boolean,
    primary: Color,
    primaryContainer: Color,
    secondary: Color,
    secondaryContainer: Color,
    tertiary: Color,
    tertiaryContainer: Color,
    background: Color,
    surface: Color,
    surfaceLow: Color,
    surfaceContainer: Color,
    surfaceHigh: Color,
    text: Color,
    mutedText: Color,
    outline: Color,
): ColorScheme {
    val base = if (darkTheme) darkColorScheme() else lightColorScheme()
    val onAccent = if (darkTheme) background else Color.White
    return base.copy(
        primary = primary,
        onPrimary = onAccent,
        primaryContainer = primaryContainer,
        onPrimaryContainer = text,
        inversePrimary = primaryContainer,
        secondary = secondary,
        onSecondary = onAccent,
        secondaryContainer = secondaryContainer,
        onSecondaryContainer = text,
        tertiary = tertiary,
        onTertiary = onAccent,
        tertiaryContainer = tertiaryContainer,
        onTertiaryContainer = text,
        background = background,
        onBackground = text,
        surface = surface,
        onSurface = text,
        surfaceVariant = surfaceHigh,
        onSurfaceVariant = mutedText,
        surfaceTint = primary,
        inverseSurface = text,
        inverseOnSurface = background,
        outline = outline,
        outlineVariant = surfaceHigh,
        scrim = Color.Black,
        surfaceBright = if (darkTheme) surfaceHigh else surface,
        surfaceDim = if (darkTheme) background else surfaceHigh,
        surfaceContainerLowest = background,
        surfaceContainerLow = surfaceLow,
        surfaceContainer = surfaceContainer,
        surfaceContainerHigh = surfaceHigh,
        surfaceContainerHighest = surfaceHigh,
        error = if (darkTheme) Color(0xFFFFB4AB) else Color(0xFFBA1A1A),
        onError = if (darkTheme) Color(0xFF690005) else Color.White,
        errorContainer = if (darkTheme) Color(0xFF93000A) else Color(0xFFFFDAD6),
        onErrorContainer = if (darkTheme) Color(0xFFFFDAD6) else Color(0xFF410002),
    )
}
